const VALID_SUBJECTS = new Set(['Mathematics', 'Science', 'Geography', 'History']);
const VALID_DIFFICULTIES = new Set(['easy', 'medium', 'challenging']);

export function isValidQuestion(q) {
  if (!q || typeof q !== 'object') return false;
  if (typeof q.id !== 'number' && typeof q.id !== 'string') return false;
  if (!VALID_SUBJECTS.has(q.subject)) return false;
  if (!VALID_DIFFICULTIES.has(q.difficulty)) return false;
  if (typeof q.question !== 'string' || !q.question.trim()) return false;
  if (!Array.isArray(q.options) || q.options.length !== 4) return false;
  if (q.options.some((opt) => typeof opt !== 'string' || !opt.trim())) return false;
  if (
    typeof q.correctAnswer !== 'number' ||
    !Number.isInteger(q.correctAnswer) ||
    q.correctAnswer < 0 ||
    q.correctAnswer > 3
  ) {
    return false;
  }
  if (typeof q.explanation !== 'string' || !q.explanation.trim()) return false;
  return true;
}

export function validateQuestionBank(questions = QUESTIONS) {
  const seenIds = new Set();
  const valid = [];

  for (const q of questions) {
    if (!isValidQuestion(q)) {
      if (import.meta.env?.DEV) {
        console.warn('[LearnRush] Skipping malformed question:', q);
      }
      continue;
    }
    if (seenIds.has(q.id)) {
      if (import.meta.env?.DEV) {
        console.warn(`[LearnRush] Duplicate question id detected (${q.id}):`, q);
      }
      continue;
    }
    seenIds.add(q.id);
    valid.push(q);
  }

  return valid;
}

export const VALIDATED_QUESTIONS = validateQuestionBank(QUESTIONS);
